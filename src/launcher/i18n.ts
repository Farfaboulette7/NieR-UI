const STRINGS: Record<Lang, Record<StringKey, string>> = { fr, en };

export const lang = (): Lang => getSettings().language;

/** Texte traduit ; {nom} est remplacé par vars.nom. */
export function t(key: StringKey, vars?: Record<string, string | number>): string {
  let s = STRINGS[lang()]?.[key] ?? fr[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Locale pour les dates et le tri (fr-FR, en-US). */
export const locale = () => (lang() === "fr" ? "fr-FR" : "en-US");

/** Langue des API Steam (Magasin, liste de souhaits). */
export const steamLanguage = () => (lang() === "fr" ? "french" : "english");
